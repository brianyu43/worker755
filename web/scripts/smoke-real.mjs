// Drives the real server through the Vite proxy: clock in, run commands, edit, report, reload and resume.
import { chromium } from 'playwright';
const base = process.argv[2] ?? 'http://127.0.0.1:5755';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on('pageerror', (e) => console.log('PAGE ERROR', e.message));
page.on('console', (m) => m.type() === 'error' && console.log('console error', m.text()));
const type = async (l) => { await page.keyboard.type(l, { delay: 5 }); await page.keyboard.press('Enter'); await page.waitForTimeout(200); };
await page.goto(base);
await page.waitForSelector('select');
console.log('models:', await page.$$eval('option', (o) => o.map((x) => x.textContent)));
await page.keyboard.press('Enter');
await page.waitForSelector('.order-title', { timeout: 30000 });
console.log('instruction:', await page.textContent('.order-title'));
console.log('text:', (await page.textContent('.order-text')).slice(0, 300));
await type('pwd');
await type('mkdir -p notes && ls -l');
await type('nano notes/a.txt');
await page.waitForSelector('.editor-text');
await page.keyboard.type('hello\n');
await page.keyboard.press('Control+s');
await page.waitForSelector('.editor', { state: 'detached' });
await type('cat notes/a.txt');
console.log('terminal tail:', (await page.$$eval('.tl', (l) => l.slice(-6).map((x) => x.textContent))).join(' | '));
await page.keyboard.press('Control+Enter');
await page.waitForSelector('.fi-result', { timeout: 15000 });
console.log('told:', (await page.textContent('.fi-result .told')).slice(0, 300));
const before = await page.$$eval('.fi-wrap', (x) => x.length);
await page.reload();
await page.waitForSelector('.fi-wrap');
await page.waitForTimeout(1500);
const seqs = await page.$$eval('.fi-wrap', (x) => x.length);
console.log('feed items before reload', before, 'after', seqs, 'url', page.url());
console.log('tree has a.txt:', await page.$$eval('.tree-name', (n) => n.some((x) => x.textContent === 'a.txt')));
await page.screenshot({ path: 'screenshots/tmp/real-1440.png' });
await browser.close();
